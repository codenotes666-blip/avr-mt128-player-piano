function createSvgElement(name, attributes) {
  const element = document.createElementNS('http://www.w3.org/2000/svg', name);
  Object.entries(attributes).forEach(([key, value]) => element.setAttribute(key, value));
  return element;
}

function pinExplanation(connector, signal, fallback) {
  return contextualGlossary[`${connector}:${signal}`] || signalGlossary[signal] || [signal, fallback || 'Board signal exposed on this connector.'];
}

function moveTooltip(event) {
  const margin = 12;
  const width = tooltip.offsetWidth || 310;
  const height = tooltip.offsetHeight || 80;
  const left = Math.min(event.clientX + 15, window.innerWidth - width - margin);
  const top = Math.min(event.clientY + 15, window.innerHeight - height - margin);
  tooltip.style.left = `${Math.max(margin, left)}px`;
  tooltip.style.top = `${Math.max(margin, top)}px`;
}

function highlightPin(index, active, event) {
  document.querySelector(`.wire-row[data-pin-index="${index}"]`)?.classList.toggle('highlighted', active);
  document.querySelectorAll(`#wireLayer [data-pin-index="${index}"]`).forEach((element) => element.classList.toggle('highlighted', active));
  if (!active) {
    tooltip.classList.remove('visible');
    return;
  }
  const row = document.querySelector(`.wire-row[data-pin-index="${index}"]`);
  const signal = row?.dataset.signal || row?.querySelector('strong')?.textContent.trim() || `Pin ${index + 1}`;
  const fallback = row?.querySelector('span')?.textContent.trim();
  const [name, description] = pinExplanation(selectedConnector, signal, fallback);
  tooltip.style.setProperty('--tooltip-color', colors[index % colors.length]);
  tooltip.querySelector('strong').textContent = `Pin ${index + 1}: ${signal} — ${name}`;
  tooltip.querySelector('span').textContent = description;
  tooltip.classList.add('visible');
  if (event) moveTooltip(event);
}

function bindPinHover(element, index) {
  element.dataset.pinIndex = index;
  element.addEventListener('mouseenter', (event) => highlightPin(index, true, event));
  element.addEventListener('mousemove', moveTooltip);
  element.addEventListener('mouseleave', () => highlightPin(index, false));
}

function drawWires(id) {
  const workspace = document.getElementById('wireWorkspace');
  const photo = document.getElementById('photoWrap');
  const layer = document.getElementById('wireLayer');
  const rows = [...document.querySelectorAll('#wireRows .wire-row')];
  const points = pinPositions[id] || [];
  const workspaceRect = workspace.getBoundingClientRect();
  const photoRect = photo.getBoundingClientRect();
  layer.replaceChildren();
  layer.setAttribute('viewBox', `0 0 ${workspaceRect.width} ${workspaceRect.height}`);

  rows.forEach((row, index) => {
    if (!points[index]) return;
    const rowRect = row.getBoundingClientRect();
    const [pixelX, pixelY] = points[index];
    const startX = photoRect.left - workspaceRect.left + photoRect.width * (pixelX / photoSize.width);
    const startY = photoRect.top - workspaceRect.top + photoRect.height * (pixelY / photoSize.height);
    const endX = rowRect.left - workspaceRect.left;
    const endY = rowRect.top - workspaceRect.top + rowRect.height / 2;
    const bendX = startX + Math.max(28, (endX - startX) * .52);
    const color = colors[index % colors.length];
    const path = createSvgElement('path', { d: `M ${startX} ${startY} C ${bendX} ${startY}, ${bendX} ${endY}, ${endX} ${endY}`, stroke: color, class: 'pin-wire' });
    const circle = createSvgElement('circle', { cx: startX, cy: startY, r: 9, fill: color, class: 'pin-node' });
    const label = createSvgElement('text', { x: startX, y: startY + .5, class: 'pin-number' });
    label.textContent = String(index + 1);
    bindPinHover(path, index);
    bindPinHover(circle, index);
    label.dataset.pinIndex = index;
    layer.append(path, circle, label);
  });
}

function populateRows(id) {
  const source = document.getElementById(id);
  const rows = document.getElementById('wireRows');
  const pins = [...source.querySelectorAll('.pin-grid > div')];
  document.getElementById('wireKind').textContent = source.querySelector('.card-heading > span').textContent;
  document.getElementById('wireTitle').textContent = source.querySelector('h2').textContent;
  rows.innerHTML = '';
  pins.forEach((pin, index) => {
    const row = document.createElement('div');
    row.className = 'wire-row';
    row.dataset.pinIndex = index;
    row.style.setProperty('--wire-color', colors[index % colors.length]);
    row.innerHTML = pin.innerHTML;
    const badge = row.querySelector('b')?.textContent.trim() || '';
    const label = row.querySelector('strong')?.textContent.trim() || `Pin ${index + 1}`;
    const signal = /^\d+$/.test(badge) ? label : badge;
    row.dataset.signal = signal;
    const fallback = row.querySelector('span')?.textContent.trim();
    const [name, description] = pinExplanation(id, signal, fallback);
    row.setAttribute('aria-label', `Pin ${index + 1}, ${signal}, ${name}. ${description}`);
    bindPinHover(row, index);
    rows.appendChild(row);
  });
}

function selectConnector(id) {
  selectedConnector = id;
  tooltip.classList.remove('visible');
  document.querySelectorAll('[data-target]').forEach((item) => item.classList.toggle('active', item.dataset.target === id));
  populateRows(id);
  requestAnimationFrame(() => drawWires(id));
  history.replaceState(null, '', `#${id}`);
}

function buildSearchIndex() {
  const entries = [];
  document.querySelectorAll('.connector-card').forEach((connector) => {
    const connectorId = connector.id;
    const connectorTitle = connector.querySelector('h2').textContent.trim();
    connector.querySelectorAll('.pin-grid > div').forEach((pin, index) => {
      const badge = pin.querySelector('b')?.textContent.trim() || String(index + 1);
      const label = pin.querySelector('strong')?.textContent.trim() || badge;
      const signal = /^\d+$/.test(badge) ? label : badge;
      const fallback = pin.querySelector('span')?.textContent.trim() || '';
      const [expanded, description] = pinExplanation(connectorId, signal, fallback);
      entries.push({
        connectorId,
        connectorTitle,
        pinIndex: index,
        pinNumber: index + 1,
        signal,
        expanded,
        description,
        haystack: `${connectorId} ${connectorTitle} ${connectorAliases[connectorId] || ''} ${signal} ${label} ${expanded} ${description} ${fallback}`.toLowerCase(),
      });
    });
  });
  return entries;
}

const searchIndex = buildSearchIndex();

function rankMatch(entry, query) {
  const signal = entry.signal.toLowerCase();
  const expanded = entry.expanded.toLowerCase();
  if (signal === query) return 0;
  if (signal.startsWith(query)) return 1;
  if (expanded.startsWith(query)) return 2;
  if (entry.connectorId.startsWith(query)) return 3;
  return 4;
}

function renderSearchResults(query) {
  const results = document.getElementById('pinSearchResults');
  activeSearchIndex = -1;
  if (!query) {
    searchMatches = [];
    results.classList.remove('visible');
    results.innerHTML = '';
    return;
  }
  const normalized = query.toLowerCase().trim();
  searchMatches = searchIndex
    .filter((entry) => entry.haystack.includes(normalized))
    .sort((left, right) => rankMatch(left, normalized) - rankMatch(right, normalized) || left.connectorTitle.localeCompare(right.connectorTitle) || left.pinNumber - right.pinNumber)
    .slice(0, 30);
  results.innerHTML = '';
  if (!searchMatches.length) {
    results.innerHTML = '<div class="pin-search-empty">No matching pins or functions.</div>';
  } else {
    searchMatches.forEach((entry, index) => {
      const button = document.createElement('button');
      button.className = 'pin-search-result';
      button.dataset.resultIndex = index;
      button.setAttribute('role', 'option');
      button.innerHTML = `<span class="result-location">${entry.connectorTitle}<br>Pin ${entry.pinNumber}</span><span><strong>${entry.signal} — ${entry.expanded}</strong><span>${entry.description}</span></span>`;
      button.addEventListener('click', () => selectSearchResult(index));
      results.appendChild(button);
    });
  }
  results.classList.add('visible');
}

function selectSearchResult(index) {
  const entry = searchMatches[index];
  if (!entry) return;
  selectConnector(entry.connectorId);
  document.getElementById('pinSearchResults').classList.remove('visible');
  document.querySelector('.board-map').scrollIntoView({ behavior: 'smooth', block: 'start' });
  setTimeout(() => {
    const row = document.querySelector(`.wire-row[data-pin-index="${entry.pinIndex}"]`);
    if (!row) return;
    const rect = row.getBoundingClientRect();
    highlightPin(entry.pinIndex, true, { clientX: rect.left, clientY: rect.top + rect.height / 2 });
  }, 450);
}

function setActiveSearchResult(index) {
  const buttons = [...document.querySelectorAll('.pin-search-result')];
  if (!buttons.length) return;
  activeSearchIndex = (index + buttons.length) % buttons.length;
  buttons.forEach((button, buttonIndex) => button.classList.toggle('active', buttonIndex === activeSearchIndex));
  buttons[activeSearchIndex].scrollIntoView({ block: 'nearest' });
}

